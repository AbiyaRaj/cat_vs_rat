// Extracts a tileable grey "fur detail" texture (fine hair strands only: colour and stripes removed) from a photo-real
// cat image, for the game to multiply into every fur texture.
//   node tools/make-fur-detail.mjs <image.png> <x> <y> <size>   ->  src/game/furDetail.js
// x, y, size: a square crop of plain flank fur. The crop is rotated so hair that runs along the spine in the
// image runs along the body (texture v) in the game.
import fs from 'node:fs'; import { PNG } from 'pngjs';
const [file, X = '620', Y = '430', SZ = '256'] = process.argv.slice(2);
const p = PNG.sync.read(fs.readFileSync(file)), x0 = +X, y0 = +Y, S = +SZ, N = 256;
// luminance crop, resampled to N×N and rotated 90° (image x -> texture y)
const L = new Float32Array(N * N);
for (let ty = 0; ty < N; ty++) for (let tx = 0; tx < N; tx++) {
  const sx = x0 + (ty + .5) * S / N, sy = y0 + (tx + .5) * S / N, i = ((sy | 0) * p.width + (sx | 0)) * 4;
  L[ty * N + tx] = (.3 * p.data[i] + .59 * p.data[i + 1] + .11 * p.data[i + 2]) / 255; }
// high-pass: subtract a wide box blur (removes stripes and shading, keeps strands)
const blur = (src, r) => { const t = new Float32Array(N * N), o = new Float32Array(N * N);
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) { let s = 0; for (let k = -r; k <= r; k++) s += src[y * N + ((x + k + N) % N)]; t[y * N + x] = s / (2 * r + 1); }
  for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) { let s = 0; for (let k = -r; k <= r; k++) s += t[((y + k + N) % N) * N + x]; o[y * N + x] = s / (2 * r + 1); }
  return o; };
const B = blur(blur(L, 4), 4), H = L.map((v, i) => v - B[i]);
// make it tile: blend four half-offset copies, each faded to zero along its own seams (weights sum to 1)
const T = new Float32Array(N * N), h = N / 2, at = (x, y) => H[(y % N) * N + (x % N)];
for (let y = 0; y < N; y++) for (let x = 0; x < N; x++) {
  const sx = Math.sin(Math.PI * x / N) ** 2, sy = Math.sin(Math.PI * y / N) ** 2;
  const v = at(x, y) * sx * sy + at(x + h, y) * (1 - sx) * sy + at(x, y + h) * sx * (1 - sy) + at(x + h, y + h) * (1 - sx) * (1 - sy);
  T[y * N + x] = v / Math.sqrt(sx * sx * sy * sy + (1 - sx) ** 2 * sy * sy + sx * sx * (1 - sy) ** 2 + (1 - sx) ** 2 * (1 - sy) ** 2); }
// normalise contrast to 0..255 around 128
let m = 0; for (const v of T) m += v * v; const sd = Math.sqrt(m / T.length) || 1;
const out = Buffer.alloc(N * N); for (let i = 0; i < N * N; i++) out[i] = Math.max(0, Math.min(255, Math.round(128 + T[i] / sd * 42)));
fs.writeFileSync('src/game/furDetail.js', `// generated by tools/make-fur-detail.mjs from a photo-real cat image: ${N}x${N} grey hair-strand detail, 128 = neutral\n` +
  `export const FUR_DETAIL={size:${N},data:'${out.toString('base64')}'};\n`);
console.log('wrote src/game/furDetail.js', (out.length / 1024).toFixed(0) + 'KB raw');
// preview
const pv = new PNG({ width: N * 2, height: N * 2 }); for (let y = 0; y < N * 2; y++) for (let x = 0; x < N * 2; x++) { const v = out[(y % N) * N + (x % N)], o = (y * N * 2 + x) * 4; pv.data[o] = pv.data[o + 1] = pv.data[o + 2] = v; pv.data[o + 3] = 255; }
if (process.env.PREVIEW) fs.writeFileSync(process.env.PREVIEW, PNG.sync.write(pv));
